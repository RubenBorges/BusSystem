import std;

import Components;
import DatabaseComponent;
import DataBus;
import EventType;
import Graph;
import LoggingComponent;
import NotifyingComponent;
import Pqxx;

namespace {

constexpr std::string_view DemoTable{"designed_system_demo"};
constexpr std::string_view DatabaseStatusSubscription{"main-database-status"};

std::string connectionString() {
    if (const char* dsn = std::getenv("DESIGNED_SYSTEM_DSN"); dsn && *dsn) {
        return dsn;
    }
    return "dbname=postgres user=postgres hostaddr=127.0.0.1 port=5432";
}

void ensureDemoTable(std::string_view dsn) {
    pqxx::connection connection{std::string{dsn}};
    pqxx::work transaction{connection};
    transaction.exec(
        "CREATE TABLE IF NOT EXISTS designed_system_demo ("
        "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
        "created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, "
        "type SMALLINT NOT NULL, "
        "message TEXT NOT NULL)");
    transaction.commit();
}

int insertDemoNotification(DatabaseComponent& database, const NotifyEvent& event) {
    database.setTableName(DemoTable);
    database.addArgs({"type", "message"});
    database.addVals(static_cast<int>(event.type), event.message);
    database.buildTransactionFromArgsandVals();

    if (database.transactionState != txnState::valid) {
        return 1;
    }
    return database.processTransaction();
}

std::string_view statusName(DatabaseTx::Status status) {
    switch (status) {
    case DatabaseTx::Status::Waiting: return "waiting";
    case DatabaseTx::Status::Fail: return "failed";
    case DatabaseTx::Status::Success: return "succeeded";
    }
    return "unknown";
}

} // namespace
//THIS IS JUST A SIMULATED DEMO TO TEST FUNCTIONALITY WHILE BUILDING!
int main() {
    DataBus bus;
    LoggingComponent logger(bus, "designed-system.log");
    NotifyingComponent notifier(bus);
    const std::string dsn = connectionString();
    DatabaseComponent database(bus, dsn);

    bool loggerStarted = false;
    bool notifierStarted = false;
    bool databaseStarted = false;
    int result = 0;

    try {
        logger.start();
        loggerStarted = true;
        notifier.start();
        notifierStarted = true;

        {
            DataBus graphRootBus;
            DataBus graphPeerBus;
            Process graphRoot{100};
            Process graphPeer{101};
            graphRoot.addChild(&graphPeer);
            graphRoot.registerChannel(
                graphPeer.identity,
                PointerChannel<Process>(&graphPeer));
            graphPeer.registerChannel(
                graphRoot.identity,
                PointerChannel<Process>(&graphRoot));

            NotifyingComponent graphRootNotifier{graphRootBus, graphRoot};
            NotifyingComponent graphPeerNotifier{graphPeerBus, graphPeer};
            graphRootNotifier.start();
            graphPeerNotifier.start();
            graphRootBus.publish(NotifyEvent{
                .type = NotifyEvent::Type::Sys,
                .now = std::chrono::system_clock::now(),
                .message = "Graph demo: this notification is delivered to the simulated peer"
            });
        }

        bus.subscribe<DatabaseTx>(
            DatabaseStatusSubscription,
            [&bus](const DatabaseTx& event) {
                const auto now = std::chrono::system_clock::now();
                const std::string message = std::format(
                    "Database {} transaction {}",
                    event.mode == DatabaseTx::Mode::Write ? "write" : "read",
                    statusName(event.status));
                const auto logType = event.status == DatabaseTx::Status::Fail
                    ? LogEntry::Type::Error
                    : LogEntry::Type::Note;
                const auto notifyType = event.status == DatabaseTx::Status::Fail
                    ? NotifyEvent::Type::Error
                    : NotifyEvent::Type::Note;

                bus.publish(LogEntry{
                    .type = logType,
                    .now = now,
                    .message = message
                });
                bus.publish(NotifyEvent{
                    .type = notifyType,
                    .now = now,
                    .message = message
                });
            });

        ensureDemoTable(dsn);
        database.start();
        databaseStarted = true;

        const auto now = std::chrono::system_clock::now();
        const NotifyEvent demoEvent{
            .type = NotifyEvent::Type::Sys,
            .now = now,
            .message = "DesignedSystem demo transaction"
        };
        bus.publish(LogEntry{
            .type = LogEntry::Type::Sys,
            .now = now,
            .message = demoEvent.message
        });
        bus.publish(demoEvent);

        result = insertDemoNotification(database, demoEvent);
    } catch (const std::exception& error) {
        std::cerr << "[DesignedSystem] " << error.what() << '\n';
        result = 1;
    }

    if (databaseStarted) {
        database.stop();
    }
    bus.unsubscribe<DatabaseTx>(DatabaseStatusSubscription);
    if (notifierStarted) {
        notifier.stop();
    }
    if (loggerStarted) {
        logger.stop();
    }

    return result;
}
